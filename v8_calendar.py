"""v8_calendar.py — v8 **唯一**零依赖静态权威交易日历（离线兜底源）

存在意义
--------
在线交易日历（akshare `tool_trade_date_hist_sina`）是首选；但它需要 akshare
+ 跨境网络。以下两类环境**必然拿不到**它：
  · 依赖尚未安装的 workflow 早期步骤（如 v8_cn_fetch_cloud 的历史步骤序）；
  · 只装了系统 python3、不装第三方库的轻量 job（如 v8_build_deploy 的 gate job）。
此时各脚本原先各自兜底（`weekday() < 5` / `return True`）⇒ **法定假日误判为交易日**
（2026-09-25 中秋实证：V8_DATA_DATE 被标成休市日当天 + 全量空转 ≥95 档）。

因此把静态区间抽到本模块（零 import、零副作用、可被任何环境加载）。

🔴 维护铁律
----------
1. 本文件是静态日历的**唯一权威源**；其他文件**禁**再硬编码节假日区间。
   （历史遗留：`guard_v8_freshness.py` 内仍有同名常量，值与本文件同源，待合流。）
2. `MAKEUP_DAYS`（周末调休上班日）**不得**视为 A 股交易日 —— A 股周末一律休市。
   该常量仅为兼容既有「工作日」语义保留，交易日判定**只**用 `HOLIDAY_RANGES`。
3. 在线日历可用时一律以在线为准，本表仅作兜底。
4. 每年沪深北交易所休市公告发布后更新本文件，并同批通知双机。

来源：国务院办公厅 2026 年节假日安排 + 沪深北交易所休市公告。
"""

# 法定休市区间（含端点，ISO 'YYYY-MM-DD'）——**交易日判定的唯一静态依据**
HOLIDAY_RANGES = [
    ("2026-01-01", "2026-01-03"),   # 元旦
    ("2026-02-15", "2026-02-23"),   # 春节
    ("2026-04-04", "2026-04-06"),   # 清明
    ("2026-05-01", "2026-05-05"),   # 劳动节
    ("2026-06-19", "2026-06-21"),   # 端午
    ("2026-09-25", "2026-09-27"),   # 中秋（09-28 周一开市）
    ("2026-10-01", "2026-10-07"),   # 国庆（10-08 开市）
]

# 周末调休上班日（**非** A 股交易日；仅部分守卫脚本按「工作日」语义使用）
MAKEUP_DAYS = {
    "2026-01-04", "2026-02-14", "2026-02-28",
    "2026-05-09", "2026-09-20", "2026-10-10",
}

# 本表覆盖的年份（超出范围时调用方须自行回落）
COVERED_YEARS = (2026,)


def in_holiday_range(iso_date: str) -> bool:
    """iso_date（'YYYY-MM-DD'）是否落在已登记法定休市区间内。"""
    for start, end in HOLIDAY_RANGES:
        if start <= iso_date <= end:
            return True
    return False


def covers(iso_date: str) -> bool:
    """本表是否覆盖该日期所在年份（未覆盖时不应据此断言「是交易日」）。"""
    try:
        return int(iso_date[:4]) in COVERED_YEARS
    except Exception:
        return False
