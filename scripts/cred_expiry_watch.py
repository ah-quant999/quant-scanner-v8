#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""cred_expiry_watch.py — 凭证到期巡检（防复发版，2026-11-15）

【为什么需要它】
凭证台账曾硬编码 updated 在 index.html，续期后易遗忘 → 长期显示假「超期」。
本脚本把「台账日期」改为**读 token json 文件的 updated 字段**（真源），实现：
  1. 同步部署镜像 data/CRED_LEDGER.js（前端台账直接读它，永不与现实脱节）；
  2. 计算各凭证剩余天数；
  3. 到期 ≤7 天或已超期 → 退出码 10，供调度自动化发邮件 2814546@qq.com 预警。

【真源文件】
  data/zsxq_token.json   → { "updated": "YYYY-MM-DD", "token": "..." }
  data/maharo_token.json → { "updated": "YYYY-MM-DD" }
  （均 .gitignore 保护，不进 git；仅本机 / CN runner 可读）

【用法】
  python scripts/cred_expiry_watch.py
  退出：0 = 全部有效（静默）；10 = 有凭证临近/超期（触发邮件）
"""
import os, json, sys, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# key -> (真源文件路径, 默认复核周期)
TOKEN_FILES = {
    "zsxq":   ("data/zsxq_token.json", 30),
    "maharo": ("data/maharo_token.json", 30),
}
# qqmail 无 token json（配置在 .workbuddy/v8_smtp_config.json，且无 updated 字段），用兜底值
QQMAIL_DEFAULT = ("2026-09-11", 90)

# 兜底（真源文件缺失时），与 index.html 硬编码默认值一致
DEFAULTS = {
    "zsxq":   ("2026-11-14", 30),
    "maharo": ("2026-11-14", 30),
}


def _pd(s):
    try:
        return datetime.datetime.strptime(str(s), "%Y-%m-%d").date()
    except Exception:
        return None


def main():
    today = datetime.date.today()
    ledger = {}
    alerts = []

    for key, (rel, cyc) in TOKEN_FILES.items():
        updated, real_cycle = None, cyc
        fp = os.path.join(ROOT, rel)
        if os.path.isfile(fp):
            try:
                d = json.load(open(fp, encoding="utf-8"))
                updated = d.get("updated")
                if d.get("cycle"):
                    real_cycle = d["cycle"]
            except Exception:
                pass
        if not updated:
            updated, real_cycle = DEFAULTS.get(key, (None, cyc))
        ud = _pd(updated)
        left = None if ud is None else real_cycle - (today - ud).days
        ledger[key] = {"updated": updated, "cycle": real_cycle}
        flag = "✅" if (left is None or left > 7) else "⚠️"
        print("[%s] updated=%s cycle=%s left=%s %s" % (key, updated, real_cycle, left, flag))
        if left is not None and left <= 7:
            alerts.append((key, left))

    # qqmail（无 json 真源，用兜底）
    qd, qc = QQMAIL_DEFAULT
    ql = qc - (today - _pd(qd)).days
    ledger["qqmail"] = {"updated": qd, "cycle": qc}
    print("[qqmail] updated=%s cycle=%s left=%s %s" % (qd, qc, ql, "✅" if ql > 7 else "⚠️"))
    if ql <= 7:
        alerts.append(("qqmail", ql))

    # 写部署镜像（前端台账直接读）
    out = os.path.join(ROOT, "data", "CRED_LEDGER.js")
    body = ("// AUTO-GENERATED by scripts/cred_expiry_watch.py — 勿手动改，改 data/*_token.json 的 updated 即可\n"
            "window.CRED_LEDGER = " + json.dumps(ledger, ensure_ascii=False, indent=2) + ";\n")
    with open(out, "w", encoding="utf-8") as f:
        f.write(body)
    print("✅ wrote %s" % out)

    if alerts:
        detail = "; ".join("%s 剩%s天" % (k, l) for k, l in alerts)
        print("ALERT: %s" % detail)
        return 10
    print("ALL_OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
